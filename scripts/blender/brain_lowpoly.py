# Builds the main brain's low-poly model in Blender (src/brain/models/brain.glb and brainGlb.ts).
#
# Input: the app's procedural brain as a PLY (scripts/blender/dump_brain.ts writes it), with the
# region tint in RGB and the fold value (1 = crown of a gyrus, 0 = groove) in alpha.
# Blender deepens the folds, cuts the surface into clear triangles (collapse decimation, which keeps
# the folds and silhouette), and exports a GLB with the fold and tint as float attributes.
#
# Run with Blender 4.2+ or the `bpy` Python module:
#   blender --background --python scripts/blender/brain_lowpoly.py -- brain_hi.ply out_dir [triangles] [depth]
import base64
import os
import sys

import bpy

args = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
ply, out = args[0], args[1]
triangles = int(args[2]) if len(args) > 2 else 8000
depth = float(args[3]) if len(args) > 3 else 0.05

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.wm.ply_import(filepath=ply)
ob = bpy.context.selected_objects[0]
bpy.context.view_layer.objects.active = ob
me = ob.data
n = len(me.vertices)

# deepen the folds: grooves sink in, crowns rise, so they survive the cut to low poly
col = me.color_attributes['Col']
rgba = [0.0] * (n * 4)
col.data.foreach_get('color', rgba)
co = [0.0] * (n * 3)
nr = [0.0] * (n * 3)
me.vertices.foreach_get('co', co)
me.vertices.foreach_get('normal', nr)
for i in range(n):
    k = depth * (rgba[i * 4 + 3] - 0.6)
    co[i * 3] += nr[i * 3] * k
    co[i * 3 + 1] += nr[i * 3 + 1] * k
    co[i * 3 + 2] += nr[i * 3 + 2] * k
me.vertices.foreach_set('co', co)
me.update()

mod = ob.modifiers.new('lowpoly', 'DECIMATE')
mod.decimate_type = 'COLLAPSE'
mod.ratio = triangles / len(me.polygons)
mod.use_collapse_triangulate = True
bpy.ops.object.modifier_apply(modifier='lowpoly')
me = ob.data
n = len(me.vertices)
print('triangles', len(me.polygons), 'vertices', n)

# fold and tint as plain float attributes (_FOLD, _TINT in the GLB) so the exporter leaves them alone
col = me.color_attributes['Col']
rgba = [0.0] * (n * 4)
col.data.foreach_get('color', rgba)
srgb = lambda c: c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055  # the PLY importer made the tint linear
fold = me.attributes.new('_fold', 'FLOAT', 'POINT')
tint = me.attributes.new('_tint', 'FLOAT_VECTOR', 'POINT')
fold.data.foreach_set('value', [rgba[i * 4 + 3] for i in range(n)])
tint.data.foreach_set('vector', [srgb(rgba[i * 4 + c]) for i in range(n) for c in range(3)])
me.color_attributes.remove(col)

glb = os.path.join(out, 'brain.glb')
bpy.ops.export_scene.gltf(filepath=glb, export_format='GLB', export_normals=False, export_texcoords=False,
                          export_materials='NONE', export_vertex_color='NONE', export_attributes=True, export_yup=False)
with open(glb, 'rb') as f:
    data = base64.b64encode(f.read()).decode()
with open(os.path.join(out, 'brainGlb.ts'), 'w') as f:
    f.write("// Generated by scripts/blender/brain_lowpoly.py from brain.glb: the Blender brain model as base64,\n"
            "// so it loads the same from the dev server, a file, or the desktop app. Don't edit by hand.\n"
            f"export default '{data}';\n")
